/** Lowercase, accents removed, punctuation and extra spaces dropped, so
 * "cote d'ivoire", "Côte d’Ivoire" and "COTE DIVOIRE" all compare equal. */
export function normalise(text: string): string {
  return text
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase()
    .replace(/-/g, " ")
    .replace(/[^a-z0-9 ]+/g, "")
    .replace(/\s+/g, " ")
    .trim();
}

const BY_KEY = new Map(NATIONALITIES.map((n) => [normalise(n), n]));

/** The listed country name for what was typed or picked (case, accents
 * and punctuation ignored), or null when it isn't on the list. Aliases
 * don't count here: a parent must pick the country itself. */
export function listedNationality(value: string): string | null {
  return BY_KEY.get(normalise(value)) ?? null;
}

export function isListedNationality(value: string): boolean {
  return listedNationality(value) !== null;
}

/** The countries matching what was typed, best first: names starting with
 * it, then names with a word starting with it, then countries an alias of
 * which starts with it, then names containing it. An empty query gives the
 * whole list, Ghana first. */
export function searchNationalities(query: string): string[] {
  const q = normalise(query);
  if (q === "") return [...NATIONALITIES];
  const rank = (name: string): number | null => {
    const n = normalise(name);
    if (n.startsWith(q)) return 0;
    if (n.split(" ").some((w) => w.startsWith(q))) return 1;
    if ((NATIONALITY_ALIASES[name] ?? []).some((a) => normalise(a).startsWith(q))) return 2;
    if (n.includes(q)) return 3;
    return null;
  };
  const ranked: { name: string; r: number; i: number }[] = [];
  NATIONALITIES.forEach((name, i) => {
    const r = rank(name);
    if (r !== null) ranked.push({ name, r, i });
  });
  return ranked.sort((a, b) => a.r - b.r || a.i - b.i).map((x) => x.name);
}
