function RootShell({ children }: { children: ReactNode }) {
  return (
    <html lang="en">
      <head>
        <HeadContent />
      </head>
      <body>
        {children}
        <Scripts />
      </body>
    </html>
  );
}

function RootComponent() {
  const { queryClient } = Route.useRouteContext();
  const pathname = useRouterState({ select: (s) => s.location.pathname });
  // /accept-invite gets the same bare treatment as /login: AuthGate would
  // either bounce a still-loading invite session to /login, or (since the
  // staff row already exists by the time this link is clicked) let them
  // straight through to the app before they've set a password at all —
  // neither is right, this page needs to run outside AuthGate entirely and
  // control that transition itself.
  const isAuthFreeRoute = pathname === "/login" || pathname === "/accept-invite";

  return (
    <QueryClientProvider client={queryClient}>
      <ThemeProvider>
        {/* Outside the auth-free/AppShell split on purpose — a dropped
            connection matters just as much on /login as anywhere else. */}
        <OfflineBanner />
        {isAuthFreeRoute ? (
          // No AppShell (sidebar/topbar) on these screens, and no AuthGate
          // either — that would just bounce back here.
          <Outlet />
        ) : (
          <AuthGate>
            <AppShell>
              {/* Required: nested routes render here. Removing <Outlet /> breaks all child routes. */}
              <Outlet />
            </AppShell>
          </AuthGate>
        )}
        <Toaster position="top-right" richColors />
      </ThemeProvider>
    </QueryClientProvider>
  );
}
